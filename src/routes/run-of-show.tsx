import { useEffect, useRef, useState } from "react";
import { createFileRoute, Link } from "@tanstack/react-router";
import { FileSpreadsheet } from "lucide-react";
import { useServerFn } from "@tanstack/react-start";
import { useEvent } from "@/components/event-context";
import { buildTimeline } from "@/lib/run-of-show";
import { TimelineTable } from "@/components/document/timeline-table";
import { AiRunSheet } from "@/components/document/ai-run-sheet";
import { SmartReviewPanel } from "@/components/document/smart-review";
import { BriefingCenter } from "@/components/document/briefing-center";
import { ReadinessScorePanel } from "@/components/document/readiness-score";
import { CopilotPanel } from "@/components/document/copilot-panel";
import { generateRunSheet } from "@/lib/generate-run-sheet.functions";
import { exportEventToExcel } from "@/lib/excel-io";
import { reviewRunSheet, type SmartReview } from "@/lib/smart-review.functions";
import { scoreReadiness, type ReadinessReport } from "@/lib/readiness-score.functions";

export const Route = createFileRoute("/run-of-show")({
  head: () => ({
    meta: [
      { title: "Run-of-Show Document · FlowStage" },
      {
        name: "description",
        content:
          "A professional, timecoded run-of-show document with cues, talent transitions, and backstage notes.",
      },
      { property: "og:title", content: "Run-of-Show Document" },
      {
        property: "og:description",
        content: "Generated by FlowStage — operational clarity for live events.",
      },
    ],
  }),
  component: RunOfShowPage,
});

function RunOfShowPage() {
  const { event, runSheet, setRunSheet } = useEvent();
  const generateFn = useServerFn(generateRunSheet);
  const reviewFn = useServerFn(reviewRunSheet);
  const scoreFn = useServerFn(scoreReadiness);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [review, setReview] = useState<SmartReview | null>(null);
  const [reviewLoading, setReviewLoading] = useState(false);
  const [reviewError, setReviewError] = useState<string | null>(null);
  const [readiness, setReadiness] = useState<ReadinessReport | null>(null);
  const [readinessLoading, setReadinessLoading] = useState(false);
  const [readinessError, setReadinessError] = useState<string | null>(null);
  const rows = buildTimeline(event);

  const buildReviewInput = () => ({
    eventName: event.name,
    eventType: event.type,
    eventDate: event.date,
    sessions: event.sessions.map((s) => ({
      title: s.title,
      startTime: s.startTime,
      durationMin: s.durationMin,
      description: s.description,
      speakers: s.speakerIds
        .map((id) => event.speakers.find((p) => p.id === id))
        .filter(Boolean)
        .map((p) => `${p!.name} (${p!.role})`),
      moderators: s.moderatorIds
        .map((id) => event.moderators.find((p) => p.id === id))
        .filter(Boolean)
        .map((p) => `${p!.name} (${p!.role})`),
    })),
    breaks: event.breaks.map((b) => ({
      label: b.label,
      startTime: b.startTime,
      durationMin: b.durationMin,
    })),
    sponsors: event.sponsors.map((s) => ({ name: s.name, placement: s.placement })),
    avRequirements: event.avRequirements,
    templateGuidance: event.templateGuidance,
    components: (event.components ?? []).map((c) => ({
      label: c.kind,
      name: c.name,
      day: c.day,
      startTime: c.startTime,
      durationMin: c.durationMin,
      venue: c.venue,
      expectedAttendees: c.expectedAttendees,
      hosts: c.hosts,
      av: c.operationalRequirements?.av,
      staffing: c.operationalRequirements?.staffing,
      protocol: c.operationalRequirements?.protocol,
      aiContext: c.aiContext,
    })),
  });

  const handleReview = async () => {
    setReviewLoading(true);
    setReviewError(null);
    try {
      const result = await reviewFn({ data: buildReviewInput() });
      setReview(result);
    } catch (e) {
      setReviewError(e instanceof Error ? e.message : "Smart Review failed");
    } finally {
      setReviewLoading(false);
    }
  };

  const handleScore = async () => {
    setReadinessLoading(true);
    setReadinessError(null);
    try {
      const result = await scoreFn({
        data: { ...buildReviewInput(), hasRunSheet: Boolean(runSheet) },
      });
      setReadiness(result);
    } catch (e) {
      setReadinessError(e instanceof Error ? e.message : "Readiness scoring failed");
    } finally {
      setReadinessLoading(false);
    }
  };

  const handleGenerate = async () => {
    setLoading(true);
    setError(null);
    try {
      const sheet = await generateFn({
        data: {
          eventName: event.name,
          eventType: event.type,
          eventDate: event.date,
          eventEndDate: event.endDate,
          sessions: event.sessions.map((s) => ({
            title: s.title,
            startTime: s.startTime,
            durationMin: s.durationMin,
            description: s.description,
            day: s.day,
            speakers: s.speakerIds
              .map((id) => event.speakers.find((p) => p.id === id))
              .filter(Boolean)
              .map((p) => `${p!.name} (${p!.role})`),
            moderators: s.moderatorIds
              .map((id) => event.moderators.find((p) => p.id === id))
              .filter(Boolean)
              .map((p) => `${p!.name} (${p!.role})`),
          })),
          breaks: event.breaks.map((b) => ({
            label: b.label,
            startTime: b.startTime,
            durationMin: b.durationMin,
            day: b.day,
          })),
          sponsors: event.sponsors.map((s) => ({ name: s.name, placement: s.placement })),
          avRequirements: event.avRequirements,
          templateGuidance: event.templateGuidance,
        },

      });
      setRunSheet(sheet);
    } catch (e) {
      setError(e instanceof Error ? e.message : "Generation failed");
    } finally {
      setLoading(false);
    }
  };

  const autoTriggered = useRef(false);
  useEffect(() => {
    if (!runSheet && !loading && !autoTriggered.current) {
      autoTriggered.current = true;
      void handleGenerate();
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const reviewAutoTriggered = useRef(false);
  useEffect(() => {
    if (runSheet && !review && !reviewLoading && !reviewAutoTriggered.current) {
      reviewAutoTriggered.current = true;
      void handleReview();
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [runSheet]);

  const lastScoredSheet = useRef<unknown>(null);
  useEffect(() => {
    if (runSheet && lastScoredSheet.current !== runSheet && !readinessLoading) {
      lastScoredSheet.current = runSheet;
      void handleScore();
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [runSheet]);


  const moderationNotes = rows
    .filter((r) => r.moderationNote)
    .map((r) => `${r.time} — ${r.moderationNote}`);
  const backstageNotes = rows
    .filter((r) => r.backstageNote)
    .map((r) => `${r.time} — ${r.backstageNote}`);

  const formattedDate = event.date
    ? new Date(event.date).toLocaleDateString("en-US", {
        weekday: "long",
        year: "numeric",
        month: "long",
        day: "numeric",
      })
    : "";

  const startTime = rows[0]?.time ?? "—";

  return (
    <div className="mx-auto max-w-6xl px-6 py-12">
      {/* Toolbar */}
      <div className="no-print mb-8 flex flex-wrap items-center justify-between gap-4">
        <div>
          <p className="font-mono text-[11px] font-bold uppercase tracking-[0.25em] text-accent">
            Document Preview
          </p>
          <h1 className="mt-1 text-2xl font-semibold tracking-tight text-navy">{event.name}</h1>
        </div>
        <div className="flex flex-wrap items-center gap-3">
          <Link
            to="/generate"
            className="rounded-md border border-border bg-background px-4 py-2 text-sm font-medium text-foreground transition-all hover:border-accent/30 hover:bg-surface"
          >
            ← Back to edit
          </Link>
          <button
            type="button"
            onClick={handleGenerate}
            disabled={loading}
            className="inline-flex items-center gap-2 rounded-md bg-accent px-4 py-2 text-sm font-semibold text-accent-foreground shadow-sm transition-all hover:bg-accent/90 hover:shadow-md hover:-translate-y-px active:translate-y-0 disabled:opacity-60 disabled:hover:translate-y-0"
          >
            {loading ? (
              <>
                <span className="h-3 w-3 animate-spin rounded-full border-2 border-accent-foreground/40 border-t-accent-foreground" />
                Generating…
              </>
            ) : (
              <>✶ {runSheet ? "Regenerate" : "Generate"} Run Sheet</>
            )}
          </button>
          <Link
            to="/import"
            className="inline-flex items-center gap-1.5 rounded-md border border-border bg-background px-4 py-2 text-sm font-medium text-foreground transition-all hover:border-accent/30 hover:bg-surface"
          >
            <FileSpreadsheet className="h-4 w-4" />
            Import Excel
          </Link>
          <button
            type="button"
            onClick={() => exportEventToExcel(event)}
            className="inline-flex items-center gap-1.5 rounded-md border border-border bg-background px-4 py-2 text-sm font-medium text-foreground transition-all hover:border-accent/30 hover:bg-surface"
          >
            Export Excel
          </button>
          <button
            type="button"
            onClick={() => window.print()}
            className="inline-flex items-center gap-1.5 rounded-md bg-navy px-4 py-2 text-sm font-medium text-navy-foreground transition-all hover:bg-navy/90 hover:shadow-md"
          >
            <span>Export PDF</span>
          </button>
        </div>
      </div>


      {error && (
        <div className="no-print mb-6 rounded-md border border-destructive/30 bg-destructive/5 px-4 py-3 text-sm text-destructive animate-fade-in">
          {error}
        </div>
      )}

      {loading && !runSheet && (
        <div className="no-print mb-6 space-y-3 rounded-sm border border-border bg-surface p-6 animate-fade-in">
          <div className="flex items-center gap-3">
            <span className="h-2 w-2 animate-pulse rounded-full bg-accent" />
            <p className="font-mono text-[11px] font-bold uppercase tracking-[0.25em] text-accent">
              AI generating production document
            </p>
          </div>
          <p className="text-sm text-muted-foreground">
            Calling cues, sequencing transitions, drafting backstage notes…
          </p>
          <div className="space-y-2">
            <div className="shimmer h-2 w-3/4" />
            <div className="shimmer h-2 w-2/3" />
            <div className="shimmer h-2 w-5/6" />
          </div>
        </div>
      )}

      {(runSheet || readiness || readinessLoading || readinessError) && (
        <div className="mb-6">
          <ReadinessScorePanel
            report={readiness}
            loading={readinessLoading}
            error={readinessError}
            onRun={handleScore}
          />
        </div>
      )}

      {(runSheet || review || reviewLoading || reviewError) && (
        <div className="mb-6">
          <SmartReviewPanel
            review={review}
            loading={reviewLoading}
            error={reviewError}
            onRun={handleReview}
          />
        </div>
      )}

      {runSheet && (
        <div className="no-print mb-6">
          <CopilotPanel
            event={event}
            runSheet={runSheet}
            readiness={readiness}
            smartReview={review}
          />
        </div>
      )}

      {runSheet && (
        <div className="no-print mb-8">
          <BriefingCenter event={event} runSheet={runSheet} />
        </div>
      )}

      {/* Document */}
      <article className="rounded-sm border border-border bg-background p-8 shadow-sm sm:p-12">
        {/* Header */}
        <header className="mb-10 flex flex-wrap items-end justify-between gap-6 border-b border-navy/10 pb-8">
          <div>
            <p className="font-mono text-[10px] font-bold uppercase tracking-widest text-accent">
              Official Document // CONFIDENTIAL
            </p>
            <h2 className="mt-2 text-4xl font-bold tracking-tight text-navy">{event.name}</h2>
            <p className="mt-2 text-sm text-muted-foreground">
              {event.type}
              {formattedDate ? ` · ${formattedDate}` : ""}
            </p>
          </div>
          <div className="text-right">
            <p className="font-mono text-xs font-medium text-foreground">REV: 1.0</p>
            <p className="mt-1 text-xs text-muted-foreground">{startTime} START</p>
          </div>
        </header>

        {/* Timeline */}
        <section className="mb-10 overflow-x-auto">
          <h3 className="mb-4 font-mono text-[11px] font-bold uppercase tracking-[0.25em] text-muted-foreground">
            Timeline
          </h3>
          <div className="min-w-[700px]">
            <TimelineTable rows={rows} />
          </div>
        </section>

        {runSheet ? (
          <section className="mt-2">
            <AiRunSheet sheet={runSheet} />
          </section>
        ) : (
          <div className="grid gap-8 md:grid-cols-2">
            <NotesBlock title="Moderation Notes" items={moderationNotes} />
            <NotesBlock title="Backstage Coordination" items={backstageNotes} />
            <NotesBlock
              title="AV Reminders"
              items={[
                event.avRequirements,
                "Mic check 30 minutes prior to doors.",
                "Confirm walk-on music levels with FOH.",
                "Lower thirds queued in order of session.",
              ].filter(Boolean)}
            />
            <NotesBlock
              title="Operational Reminders"
              items={[
                "Stage manager calls all cues from booth.",
                "Green Room A reserved for keynote speakers.",
                "Holding area available stage-right 15 minutes before each session.",
                event.sponsors.length
                  ? `Sponsor acknowledgements: ${event.sponsors.map((s) => s.name).join(", ")}.`
                  : "",
              ].filter(Boolean)}
            />
          </div>
        )}

        <footer className="mt-12 border-t border-border pt-6">
          <p className="font-mono text-[10px] uppercase tracking-widest text-muted-foreground">
            Generated by FlowStage · End of document
          </p>
        </footer>
      </article>
    </div>
  );
}

function NotesBlock({ title, items }: { title: string; items: string[] }) {
  return (
    <section className="rounded-lg border border-border bg-surface p-5">
      <h4 className="font-mono text-[10px] font-bold uppercase tracking-[0.25em] text-muted-foreground">
        {title}
      </h4>
      <ul className="mt-3 space-y-2 text-sm text-foreground/90">
        {items.length === 0 && (
          <li className="text-muted-foreground italic">No notes generated.</li>
        )}
        {items.map((n, i) => (
          <li key={i} className="leading-relaxed">
            <span className="text-accent">›</span> {n}
          </li>
        ))}
      </ul>
    </section>
  );
}
